"""The reference places against the standard, and their derived legacy tags against today's cards (batch 9, m364).

Usage: python scripts/place_knowledge_report.py [--out validation/place-knowledge/reference-places]

Writes <out>.md and <out>.json. Reads only; changes no card and no plan. The planner keeps the cards' own tags until
Abram approves the switch (decisions/place-knowledge-model.md §1).
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from collections import Counter
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from brain.experiences import (INTERESTS, LEGACY_FROM, UNKNOWN, appeals, hard_facts, legacy_tags,  # noqa: E402
                               load_places, problems, unknown_share, unverified_hard)
from brain.moments import MOMENT_TAGS, PLACE_TAGS, load_moments  # noqa: E402

TODAY = date(2026, 11, 28)


def _commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip()
    except Exception:  # noqa: BLE001
        return "unknown"


def _basis(place, tag: str) -> str:
    """Why a derived tag has its value: scored evidence, unknown read as 0, or not derivable yet."""
    if tag == "walking_effort":
        exps = [place.experience(e) for e in place.legacy_from]
        return "effort" if any(e.effort is not None and e.effort.value != UNKNOWN for e in exps) else "not derivable"
    if tag not in LEGACY_FROM:
        return "not derivable"
    exps = [place.experience(e) for e in place.legacy_from]
    for e in exps:
        for s in LEGACY_FROM[tag]:
            v = e.score(s) if s in INTERESTS else e.atmos_max(s)
            if v != UNKNOWN:
                return "scored"
    return "unknown → 0"


def build(places_dir: Path, moments_dir: Path) -> dict:
    cards = {m.id: m for m in load_moments(moments_dir)}
    out = {"commit": _commit(), "date": TODAY.isoformat(), "places": []}
    status_all, source_all = Counter(), Counter()
    for p in load_places(places_dir):
        claims = p.claims()
        status_all.update(c.status for c in claims.values())
        source_all.update(c.source_type for c in claims.values())
        card = cards.get(p.legacy_card)
        derived = legacy_tags(p)
        tags = []
        for t in PLACE_TAGS + MOMENT_TAGS:
            tags.append({"tag": t, "card": card.tag(t) if card else None, "derived": derived.get(t),
                         "basis": _basis(p, t)})
        exps = []
        for e in p.experiences:
            ap = appeals(p, e)
            exps.append({
                "id": e.id, "title": e.title, "status": e.status, "activity": e.activity,
                "primary": list(e.primary), "secondary": list(e.secondary),
                "scores": {d: {"value": a.value, "status": a.status, "role": a.role} for d, a in ap.items()},
                "unknown_share": round(unknown_share(e), 2), "needs": list(e.needs)})
        hf = hard_facts(p, TODAY)
        out["places"].append({
            "id": p.id, "name": p.name, "kind": p.kind, "card": p.legacy_card, "from": list(p.legacy_from),
            "problems": problems(p, card_ids=set(cards)), "experiences": exps, "tags": tags,
            "hard_verified": sorted(hf), "hard_not_verified": [
                {"id": c.id, "type": c.fact_type, "status": c.status} for c in unverified_hard(p, TODAY)],
            "claims": dict(Counter(c.status for c in claims.values()))})
    out["claims_by_status"] = dict(status_all)
    out["claims_by_source"] = dict(source_all)
    return out


def _cell(v) -> str:
    return "–" if v is None else str(v)


def markdown(r: dict) -> str:
    L = [f"# Reference places against the standard (batch 9, generated at `{r['commit']}`, {r['date']})", "",
         "Generated by `brain/scripts/place_knowledge_report.py`. **Reads only:** no card and no plan changed; the "
         "planner keeps the cards' own tags until Abram approves the switch.", "",
         "**Status of every claim:** " + ", ".join(f"{k} {v}" for k, v in sorted(r["claims_by_status"].items())) +
         ". **By source:** " + ", ".join(f"{k} {v}" for k, v in sorted(r["claims_by_source"].items())) + ".", ""]
    for p in r["places"]:
        L += [f"## {p['name']} (`{p['id']}`, card `{p['card']}`)", "",
              "**Standard:** " + ("passes" if not p["problems"] else "FAILS: " + "; ".join(p["problems"])), "",
              "| Experience | Status | Primary | Secondary | Scored dimensions (status) | Unknown |",
              "|---|---|---|---|---|---|"]
        for e in p["experiences"]:
            sc = ", ".join(f"{d} {v['value']} ({v['status']})" for d, v in e["scores"].items())
            L.append(f"| {e['title']} | {e['status']} | {', '.join(e['primary']) or '–'} | "
                     f"{', '.join(e['secondary']) or '–'} | {sc} | {int(e['unknown_share'] * 100)}% |")
        L += ["", "**Hard facts a rule may use** (verified and current): " + (", ".join(p["hard_verified"]) or "none"),
              "", "**Hard facts it may not use** (said, never applied): " + (
                  ", ".join(f"{h['type']} ({h['status']})" for h in p["hard_not_verified"]) or "none"), ""]
        L += ["Legacy tags, worked out from " + ", ".join(f"`{x}`" for x in p["from"]) + ":", "",
              "| Tag | Card today | Derived | Basis |", "|---|---|---|---|"]
        for t in p["tags"]:
            mark = " **≠**" if t["derived"] is not None and t["card"] is not None and t["derived"] != t["card"] else ""
            L.append(f"| {t['tag']} | {_cell(t['card'])} | {_cell(t['derived'])}{mark} | {t['basis']} |")
        L.append("")
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT.parent / "validation" / "place-knowledge" / "reference-places"))
    a = ap.parse_args()
    r = build(ROOT / "data" / "places", ROOT / "data" / "moments")
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".json").write_text(json.dumps(r, indent=1, default=str))
    out.with_suffix(".md").write_text(markdown(r))
    bad = [p["id"] for p in r["places"] if p["problems"]]
    print(f"{len(r['places'])} places; failing the standard: {bad or 'none'}; written {out}.md")


if __name__ == "__main__":
    main()
