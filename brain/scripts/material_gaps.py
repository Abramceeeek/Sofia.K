"""m269 (Abram, m260, priority B): the facts that materially affect a visit, missing in London and Paris, ranked by how
often each place appears in plans. Writes benchmarks/coverage/material_gaps.md. Read-only; nothing is filled in.

Material facts (Abram: "Opening hours, accessibility, prices, geographical areas and seasonal restrictions matter more
than adding decorative descriptions"), counted as readiness.py counts them:
- hours: read on an official page in the last 180 days (or sessions known, for events);
- step-free: known (yes, partial or no) from a named source;
- price: known (a source or an estimate label);
- area: a named area or district;
- season: outdoor places with seasonal information.
London's order is each card's share of simulated personal plans (data/popularity.yaml, D113), so the top of the list is
what friends will meet most. Paris has no plans yet, so it's listed by gap count.

Run from brain/: `.venv/bin/python scripts/material_gaps.py`
"""
import sys
from datetime import date, timedelta
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
from brain.catalogue import _SEASONAL, load_catalogue, load_dev  # noqa: E402
from brain.config import DATA_DIR  # noqa: E402

TODAY = date(2026, 11, 13)
FRESH = (TODAY - timedelta(days=180)).isoformat()
OUTDOOR = {"nature", "views", "neighbourhood"}


def gaps(x) -> list[str]:
    out = []
    event = getattr(x.facet, "event_based", False)
    if not ((event and x.facet.sessions.known) or (x.hours.trust == "checked" and (x.hours.source or "").startswith(
            "https://") and x.hours.checked is not None and x.hours.checked >= FRESH)):
        out.append("hours")
    if not x.accessibility.step_free.known:
        out.append("step-free")
    if not x.price.known:
        out.append("price")
    if not (x.geo.area.known or x.district.known):
        out.append("area")
    if x.category in OUTDOOR and not (x.notices or _SEASONAL.search((x.hours.text or "").lower())):
        out.append("season")
    return out


def main() -> int:
    shares = yaml.safe_load((DATA_DIR / "popularity.yaml").read_text(encoding="utf-8"))["shares"]
    london = [x for x in load_catalogue() if x.status == "ready"]
    paris = [x for x in load_dev("paris")[1] if x.status == "ready"]
    share = lambda x: max([shares.get(i, 0.0) for i in x.legacy_ids] or [0.0])
    lines = ["# Material data gaps, by how often a place is planned (m269, 13 Nov 2026)", "",
             "Generated by `brain/scripts/material_gaps.py`. Counts only; nothing is estimated or filled in.", ""]
    for city, xs, by_share in (("London", london, True), ("Paris (development)", paris, False)):
        rows = sorted(((share(x) if by_share else None, x, gaps(x)) for x in xs),
                      key=lambda r: (-(r[0] or 0), -len(r[2]), r[1].id))
        total = {k: sum(1 for *_, g in rows if k in g) for k in ("hours", "step-free", "price", "area", "season")}
        lines += [f"## {city}: {len(xs)} ready", "",
                  "Missing: " + ", ".join(f"{k} {v}" for k, v in total.items()) + ".", "",
                  "| Place | Share of simulated plans | Missing |" if by_share else "| Place | Missing |",
                  "|---|---|---|" if by_share else "|---|---|"]
        for s, x, g in rows:
            if g:
                name = x.title or x.name
                lines.append(f"| {name} (`{x.legacy_ids[0] if x.legacy_ids else x.id}`) | {s:.0%} | {', '.join(g)} |"
                             if by_share else f"| {name} (`{x.id}`) | {', '.join(g)} |")
        if by_share:
            weight = sum(s for s, _, g in rows if g)
            lines += ["", f"Places with a gap carry {weight:.2f} of the plan-share total "
                          f"{sum(s for s, *_ in rows):.2f} (shares sum over 4 stops a plan)."]
        lines.append("")
    out = Path(__file__).resolve().parent.parent / "benchmarks" / "coverage" / "material_gaps.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:40]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
